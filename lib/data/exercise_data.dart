  static List<Exercise> getByBodyPart(String bodyPart) {
    switch (bodyPart.toLowerCase()) {
      case 'chest':
        return chest;
      case 'back':
        return back;
      case 'legs':
        return legs;
      case 'shoulders':
        return shoulders;
      case 'biceps':
        return biceps;
      case 'triceps':
        return triceps;
      case 'arms':
        return [...biceps, ...triceps];
      case 'core':
        return core;
      case 'cardio':
        return cardio;
      case 'full_body':
        return getAllExercises();
      default:
        return getAllExercises();
    }
  }

  static List<Exercise> getAllExercises() {
    return [
      ...chest,
      ...back,
      ...legs,
      ...shoulders,
      ...biceps,
      ...triceps,
      ...core,
      ...cardio,
    ];
  }

  static List<Exercise> search(String query) {
    final q = query.toLowerCase();
    return getAllExercises().where((e) {
      return e.name.toLowerCase().contains(q) ||
          e.bodyPart.toLowerCase().contains(q) ||
          e.equipment.toLowerCase().contains(q) ||
          e.instructions.toLowerCase().contains(q);
    }).toList();
  }
